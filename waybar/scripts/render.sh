#!/usr/bin/env bash
# Renders the ACTIVE waybar files (config.jsonc / style.css) from the single sources
# configs/config.jsonc and styles/style.css, applying the layout mode (.mode).
# Sizing lives directly in the sources -- there is no scale factor anymore.
#
# Usage: render.sh          (re-render using current .mode)
set -euo pipefail

DIR="$HOME/.config/waybar"

# Layout mode: float (gapped, rounded) or bar (classic full-width). Baked at
# render time so the sources stay a clean single baseline.
MODE=$(cat "$DIR/.mode" 2>/dev/null || echo float)
[[ "$MODE" == bar || "$MODE" == float ]] || MODE=float

# Mode transforms.
mode_config() {
    if [[ "$MODE" == bar ]]; then
        # Bar mode: flatten the floating margins so the surface spans
        # edge-to-edge, and drop "width" entirely (a zero width would still be
        # a fixed unanchored surface -- only removing the key restores the
        # classic anchored, content-stretched bar).
        sed -E 's/("(margin-[a-z]+)"\s*:\s*)[0-9.]+/\1 0/g; /^\s*"width"\s*:/d'
    else
        cat
    fi
}

mode_css() {
    if [[ "$MODE" == bar ]]; then
        # Bar mode: square corners, no outline -- scoped to the bar block only,
        # tooltip and tray menus keep their borders in both modes.
        sed -E '/window#waybar \{/,/^\}/ {
            s/border-radius:[[:space:]]*[0-9.]+px/border-radius: 0px/
            s/border:[[:space:]]*1px[[:space:]]+solid[[:space:]]+[^;]+;/border: none;/
        }'
    else
        cat
    fi
}

SRC_CONFIG="$DIR/configs/config.jsonc"
SRC_STYLE="$DIR/styles/style.css"
WARN="AUTO-GENERATED by scripts/render.sh -- edits here are DESTROYED on the next render."

# Atomic replace: stage each rendered file beside its target, then rename over it.
# A crash mid-render now leaves the previous good files intact instead of a
# truncated active config that launch.sh's restart loop would chew on forever.
# Both renames happen only after both renders succeed, so config/style stay a
# matched pair.
CONFIG_TMP="$DIR/config.jsonc.$$"
STYLE_TMP="$DIR/style.css.$$"
trap 'rm -f "$CONFIG_TMP" "$STYLE_TMP"' EXIT

{ printf '// %s Edit configs/config.jsonc instead.\n' "$WARN"; mode_config < "$SRC_CONFIG"; } > "$CONFIG_TMP"
{ printf '/* %s Edit styles/style.css instead. */\n' "$WARN"; mode_css < "$SRC_STYLE"; } > "$STYLE_TMP"

mv -f "$CONFIG_TMP" "$DIR/config.jsonc"
mv -f "$STYLE_TMP" "$DIR/style.css"
trap - EXIT
