#!/usr/bin/env bash
# Renders the ACTIVE waybar files (config.jsonc / style.css) from the single sources
# configs/config.jsonc and styles/style.css, applying the scale factor (.scale).
#
# Waybar is GTK3 and has no scale setting, so "scaling" means multiplying every px value in
# the CSS, the size-bearing keys in the config, and the inline Pango <span size='...'> values.
# Doing it at render time keeps the sources as a clean 1.0 baseline -- scaling is never
# applied on top of itself, so it stays lossless and repeatable.
#
# Usage: render.sh          (re-render using current .scale)
set -euo pipefail

DIR="$HOME/.config/waybar"
SCALE=$(cat "$DIR/.scale" 2>/dev/null || echo 1.0)

# Reject anything that isn't a plain positive number, then clamp to a sane range.
[[ "$SCALE" =~ ^[0-9]+(\.[0-9]+)?$ ]] || SCALE=1.0
awk -v s="$SCALE" 'BEGIN{exit !(s>=0.5 && s<=3.0)}' || SCALE=1.0

SRC_CONFIG="$DIR/configs/config.jsonc"
SRC_STYLE="$DIR/styles/style.css"
WARN="AUTO-GENERATED by scripts/render.sh -- edits here are DESTROYED on the next scale change."

scale_css() {
    perl -pe 'BEGIN{$s=shift @ARGV} s/(\d+(?:\.\d+)?)px/sprintf("%gpx", $1*$s)/ge' "$1"
}

scale_jsonc() {
    # Only size-bearing keys are scaled. Never touch "interval", "signal", "timeout", etc.
    # These are all integer-valued in waybar (a fractional "height" is not accepted), and
    # Pango sizes are integer 1/1024ths, so round rather than truncate -- plain int() turned
    # 11500 * 1.15 into 13224 instead of 13225.
    perl -pe 'BEGIN{$s=shift @ARGV}
        s/("(?:height|border-radius|icon-size|spacing|margin-(?:top|bottom|left|right))"\s*:\s*)(\d+(?:\.\d+)?)/$1 . int($2*$s + 0.5)/ge;
        s/size='"'"'(\d+)'"'"'/sprintf("size=%c%d%c", 39, int($1*$s + 0.5), 39)/ge;
    ' "$1"
}

# Atomic replace: stage each rendered file beside its target, then rename over it.
# A crash mid-render now leaves the previous good files intact instead of a
# truncated active config that launch.sh's restart loop would chew on forever.
# Both renames happen only after both renders succeed, so config/style stay a
# matched pair.
CONFIG_TMP="$DIR/config.jsonc.$$"
STYLE_TMP="$DIR/style.css.$$"
trap 'rm -f "$CONFIG_TMP" "$STYLE_TMP"' EXIT

{ printf '// %s Edit configs/config.jsonc instead.\n' "$WARN"; scale_jsonc "$SCALE" < "$SRC_CONFIG"; } > "$CONFIG_TMP"
{ printf '/* %s Edit styles/style.css instead. */\n' "$WARN"; scale_css "$SCALE" < "$SRC_STYLE"; } > "$STYLE_TMP"

mv -f "$CONFIG_TMP" "$DIR/config.jsonc"
mv -f "$STYLE_TMP" "$DIR/style.css"
trap - EXIT
